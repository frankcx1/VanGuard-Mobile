data class Coverage(val totalPages: Int = 0, val extracted: Int = 0, val empty: Int = 0, val failed: Int = 0, val chunks: Int = 0, val embedded: Int = 0, val npuEmbedded: Int = 0)
data class PageRecord(val number: Int, val title: String, val state: String)

class BinderStore(context: Context, databaseName: String = "binder.sqlite") : SQLiteOpenHelper(context, File(context.noBackupFilesDir, databaseName).path, null, 2) {
    override fun onCreate(db: SQLiteDatabase) {
        db.execSQL("CREATE TABLE metadata (name TEXT PRIMARY KEY, value TEXT NOT NULL)")
        db.execSQL("CREATE TABLE pages (number INTEGER PRIMARY KEY, text TEXT NOT NULL, state TEXT NOT NULL)")
        db.execSQL("CREATE TABLE chunks (id INTEGER PRIMARY KEY AUTOINCREMENT, page INTEGER NOT NULL, body TEXT NOT NULL, vector BLOB, fingerprint TEXT, npu_vector BLOB, npu_fingerprint TEXT)")
    }
    override fun onUpgrade(db: SQLiteDatabase, oldVersion: Int, newVersion: Int) {
        if (oldVersion == 1 && newVersion == 2) {
            db.execSQL("ALTER TABLE chunks ADD COLUMN npu_vector BLOB")
            db.execSQL("ALTER TABLE chunks ADD COLUMN npu_fingerprint TEXT")
        } else error("Unsupported binder migration")
    }
    fun setTotal(total: Int) {
        writableDatabase.execSQL("INSERT OR REPLACE INTO metadata(name,value) VALUES('page_count',?)", arrayOf(total.toString()))
        writableDatabase.execSQL("INSERT OR REPLACE INTO metadata(name,value) VALUES('source_sha256',?)", arrayOf(StarterManual.SHA256))
    }
    private fun count(sql: String, args: Array<String>? = null): Int = readableDatabase.rawQuery(sql, args).use { if (it.moveToFirst()) it.getInt(0) else 0 }
    fun coverage() = Coverage(
        count("SELECT value FROM metadata WHERE name='page_count'"),
        count("SELECT COUNT(*) FROM pages WHERE state='text'"),
        count("SELECT COUNT(*) FROM pages WHERE state='empty'"),
        count("SELECT COUNT(*) FROM pages WHERE state='error'"),
        count("SELECT COUNT(*) FROM chunks"),
        count("SELECT COUNT(*) FROM chunks WHERE vector IS NOT NULL AND fingerprint=?", arrayOf(StarterManual.FINGERPRINT)),
        count("SELECT COUNT(*) FROM chunks WHERE npu_vector IS NOT NULL AND npu_fingerprint=?", arrayOf(ComputeProfile.NPU.manualFingerprint)),
    )
    fun hasPage(number: Int): Boolean = count("SELECT COUNT(*) FROM pages WHERE number=? AND state!='error'", arrayOf(number.toString())) > 0
    fun savePage(number: Int, text: String, state: String) {
        val db = writableDatabase
        db.beginTransaction()
        try {
            db.delete("chunks", "page=?", arrayOf(number.toString()))
            db.insertWithOnConflict("pages", null, ContentValues().apply { put("number", number); put("text", text); put("state", state) }, SQLiteDatabase.CONFLICT_REPLACE)
            if (state == "text") Retrieval.chunks(text).forEach { part ->
                db.insertOrThrow("chunks", null, ContentValues().apply { put("page", number); put("body", part) })
            }
            db.setTransactionSuccessful()
        } finally { db.endTransaction() }
    }
    fun passages(profile: ComputeProfile = ComputeProfile.CPU_GPU): List<Passage> = readableDatabase.rawQuery("SELECT id,page,body,${profile.vectorColumn},${profile.fingerprintColumn} FROM chunks ORDER BY id", null).use { c ->
        buildList {
            while (c.moveToNext()) {
                val vector = if (!c.isNull(3) && c.getString(4) == profile.manualFingerprint) {
                    val blob = c.getBlob(3); val buffer = ByteBuffer.wrap(blob).order(ByteOrder.LITTLE_ENDIAN)
                    if (blob.size == 768 * 4) FloatArray(768) { buffer.float } else null
                } else null
                add(Passage(c.getLong(0), c.getInt(1), c.getString(2), vector))
            }
        }
    }
    fun saveVector(id: Long, values: FloatArray, profile: ComputeProfile = ComputeProfile.CPU_GPU) {
        require(values.size == 768 && values.all { it.isFinite() })
        val buffer = ByteBuffer.allocate(values.size * 4).order(ByteOrder.LITTLE_ENDIAN)
        values.forEach { buffer.putFloat(it) }
        writableDatabase.update("chunks", ContentValues().apply { put(profile.vectorColumn, buffer.array()); put(profile.fingerprintColumn, profile.manualFingerprint) }, "id=?", arrayOf(id.toString()))
    }
    fun pages(): List<PageRecord> = readableDatabase.rawQuery("SELECT number,text,state FROM pages ORDER BY number", null).use { c ->
        buildList { while (c.moveToNext()) add(PageRecord(c.getInt(0), c.getString(1).lineSequence().filter { it.trim().length > 3 }.take(2).joinToString(" · ").take(130), c.getString(2))) }
    }
    fun removeCopyIndex() {
        writableDatabase.beginTransaction()
        try {
            writableDatabase.delete("chunks", null, null); writableDatabase.delete("pages", null, null); writableDatabase.delete("metadata", null, null)
            writableDatabase.setTransactionSuccessful()
        } finally { writableDatabase.endTransaction() }
    }
}
